use crate::pool::{backend, pool, Backend};
use larust_core::{axum, AppError};
use sqlx::any::{Any, AnyArguments};
use sqlx::query::QueryAs;
use sqlx::AnyPool;
use std::marker::PhantomData;

/// A dynamically-typed bind value - `where_eq` accepts any of these via
/// `Into<BindValue>` so the builder can accumulate heterogeneous
/// conditions (`where_eq(Post::TITLE, "x").where_eq(Post::ID, 1)`) in one
/// `Vec` before binding them to the query at execution time.
#[derive(Clone)]
pub enum BindValue {
    Text(String),
    Int(i64),
    Bool(bool),
}

impl From<String> for BindValue {
    fn from(v: String) -> Self {
        BindValue::Text(v)
    }
}

impl From<&str> for BindValue {
    fn from(v: &str) -> Self {
        BindValue::Text(v.to_string())
    }
}

impl From<i64> for BindValue {
    fn from(v: i64) -> Self {
        BindValue::Int(v)
    }
}

impl From<bool> for BindValue {
    fn from(v: bool) -> Self {
        BindValue::Bool(v)
    }
}

/// `WHERE column <op> ?` - richer comparisons than `where_eq`'s plain
/// equality (Laravel's 3-argument `->where($col, '>', $val)`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Op {
    Ne,
    Gt,
    Gte,
    Lt,
    Lte,
    Like,
}

impl Op {
    fn as_sql(self) -> &'static str {
        match self {
            Op::Ne => "!=",
            Op::Gt => ">",
            Op::Gte => ">=",
            Op::Lt => "<",
            Op::Lte => "<=",
            Op::Like => "LIKE",
        }
    }
}

/// `.order_by(column, Order::Desc)` - Laravel's `->orderBy($col, 'desc')`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Order {
    Asc,
    Desc,
}

/// How a condition joins to the one before it. The very first entry in a
/// `wheres` list never actually renders its own `Conj` (there's nothing
/// before it to join to) - stored anyway so every entry has the same
/// shape, rather than special-casing the first element's type.
#[derive(Clone, Copy)]
enum Conj {
    And,
    Or,
}

/// One accumulated `WHERE` condition - private, built only through the
/// builder's own `where_*`/`or_where_*`/`scope`/`*_group` methods, so
/// callers never construct one directly.
#[derive(Clone)]
enum Condition {
    Eq(&'static str, BindValue),
    Op(&'static str, Op, BindValue),
    In(&'static str, Vec<BindValue>),
    Null(&'static str),
    NotNull(&'static str),
    /// `where_group`/`or_where_group`/`scope` - a parenthesized
    /// sub-clause. Carries a full nested `wheres` list (not just a single
    /// `Condition`) because a group's own contents can themselves mix
    /// `AND`/`OR`.
    Group(Vec<(Conj, Condition)>),
    /// `where_in_query` - "col" IN (SELECT sub_column FROM sub_table
    /// [WHERE ...]). Deliberately a subquery, not a real `JOIN`:
    /// `QueryBuilder` decodes every row into one `sqlx::FromRow` struct
    /// via `SELECT *`, and its column constants (`Post::TITLE`) are bare,
    /// unqualified names - both assumptions a real multi-table `JOIN`
    /// would break (ambiguous `id`, ambiguous bare column names across
    /// tables) without a breaking redesign (a qualified `Column{table,
    /// name}` type everywhere). A subquery filter needs neither change
    /// and covers the same "filter by a related table's rows"(`hasManyThrough`,
    /// Eloquent's `whereHas`) use case this was added for.
    InQuery {
        column: &'static str,
        sub_table: &'static str,
        sub_column: &'static str,
        sub_wheres: Vec<(Conj, Condition)>,
    },
}

/// How a soft-deletable `QueryBuilder` filters on its own soft-delete
/// column - only ever set to anything but `Normal` via
/// `with_trashed`/`only_trashed`, both gated to `T: SoftDeletes` (see
/// that trait's own doc comment).
#[derive(Clone, Copy)]
enum SoftDeleteFilter {
    Normal,
    WithTrashed,
    OnlyTrashed,
}

/// Laravel-shaped query builder (`Post::query().where_eq(...).latest(...)`)
/// over `sqlx`. Column names passed in (`Post::TITLE`) are `&'static str`
/// constants generated by `#[derive(Model)]`, never user input, so they're
/// interpolated directly into the SQL string; bound *values* always go
/// through placeholders - never string-formatted into the query.
pub struct QueryBuilder<T> {
    table: &'static str,
    wheres: Vec<(Conj, Condition)>,
    order_by: Vec<(&'static str, Order)>,
    limit: Option<i64>,
    /// `None` for the overwhelming majority of models (never marked
    /// `#[soft_deletes]`) - set only by the hidden setter below, which
    /// only the *generated* `query()` for a soft-deletable model calls.
    soft_delete: Option<(&'static str, SoftDeleteFilter)>,
    _marker: PhantomData<fn() -> T>,
}

/// **Known gap: a `bool`-typed field on a `#[derive(Model, sqlx::FromRow)]`
/// struct doesn't decode through `AnyRow` on SQLite.** SQLite has no native
/// boolean column type (it stores `0`/`1` as an `INTEGER`); the concrete
/// `sqlx::Sqlite` driver knows to coerce that into `bool`, but `sqlx`'s
/// backend-agnostic `Any` driver tags the column as its own generic
/// `BigInt` kind instead and refuses the conversion (confirmed
/// empirically: decoding fails with "Rust type `bool` is not compatible
/// with SQL type `BIGINT`" - MySQL's own `Any` adapter doesn't have this
/// problem, since MySQL's `TINYINT(1)`/`BOOLEAN` gets tagged correctly).
/// No current app model in this workspace has a `bool` field, so this
/// hasn't needed a real fix yet - if one ever does, decode the column as
/// `i64` and compare `!= 0` by hand instead (see
/// `larust-permissions::has_role`/`has_permission_to` for the exact
/// pattern, needed for their own `SELECT EXISTS(...)` queries).
///
/// **A second, more consequential known gap in the same family: a
/// `String`-typed field backed by a MySQL `TEXT` (or `TINYTEXT`/
/// `MEDIUMTEXT`/`LONGTEXT`) column doesn't decode through `Any` at all,
/// on *any* app model - not just framework-internal ones.** Confirmed
/// empirically against a real MySQL server: `sqlx-mysql`'s own `Any`
/// adapter maps every one of those column types to its own generic
/// `Blob` kind unconditionally (it keys off the wire-protocol
/// `ColumnType` alone, which doesn't distinguish TEXT from BLOB the way
/// the column's actual charset does), and `Decode<Any> for String` only
/// ever accepts `Text`-kind values - decoding fails with "Rust type
/// `String` is not compatible with SQL type `BLOB`". Only `CHAR`/
/// `VARCHAR` map to `Any`'s `Text` kind. **A MySQL-targeted app's own
/// migrations need `VARCHAR(n)` for any column a model reads back as
/// `String`, not `TEXT`** - every framework-owned table with its own
/// bootstrap SQL (`larust-http::session`'s `sessions.data`,
/// `larust-cache`'s `cache_items.value`, `larust-queue`'s `jobs.payload`/
/// `failed_jobs.error`, `larust-notifications`'s `notifications.data`/
/// `notification_type`, `larust-sanctum`'s `personal_access_tokens.name`)
/// already had to make this exact switch, each landing on a generous but
/// bounded `VARCHAR(4000)` (kept well under MySQL's ~65,535-byte
/// combined-row-size limit even at `utf8mb4`'s worst-case 4 bytes/char,
/// confirmed empirically against a real server - `VARCHAR(16383)` alone
/// already exceeds it once more than one such column shares a row).
/// There is no known workaround for genuinely unbounded content (a long
/// blog post body, say) beyond raising that cap and accepting the
/// row-size math, or waiting for an upstream `sqlx` fix - MySQL/`Any`
/// support in this framework is not a byte-for-byte drop-in replacement
/// for SQLite's own effectively-unlimited `TEXT` in that one specific
/// respect.
///
/// **Postgres has neither gap - confirmed empirically against a real
/// server, not just inferred from its type system.** A native `BOOLEAN`
/// column decodes straight into `bool` through `Any` with no `i64`
/// workaround needed, and a `TEXT` column of several thousand characters
/// decodes straight into `String` with no `VARCHAR(n)` cap needed -
/// Postgres's own `Any` adapter tags both correctly (`Bool`/`Text` kind),
/// unlike SQLite's/MySQL's own adapters. Every framework-owned table's
/// Postgres arm (see `larust-cache`/`larust-queue`/`larust-sanctum`/
/// `larust-notifications`/`larust-http::session`) uses plain `TEXT`, not
/// a MySQL-style `VARCHAR(4000)` cap, on the strength of this.
impl<T> QueryBuilder<T>
where
    T: for<'r> sqlx::FromRow<'r, sqlx::any::AnyRow> + Send + Unpin,
{
    pub fn new(table: &'static str) -> Self {
        Self {
            table,
            wheres: Vec::new(),
            order_by: Vec::new(),
            limit: None,
            soft_delete: None,
            _marker: PhantomData,
        }
    }

    /// Not part of the public API (hence `#[doc(hidden)]`, not a true
    /// visibility restriction - it has to be `pub` so macro-generated
    /// code in a *different* crate, an app's own, can call it). Only
    /// `#[derive(Model)]`'s generated `query()` calls this, and only for
    /// a struct marked `#[soft_deletes]` - every other call site never
    /// touches it, leaving `soft_delete` at its default `None`.
    #[doc(hidden)]
    #[must_use]
    pub fn __with_soft_delete_column(mut self, column: &'static str) -> Self {
        self.soft_delete = Some((column, SoftDeleteFilter::Normal));
        self
    }

    #[must_use]
    pub fn where_eq(mut self, column: &'static str, value: impl Into<BindValue>) -> Self {
        self.wheres
            .push((Conj::And, Condition::Eq(column, value.into())));
        self
    }

    /// `WHERE column <op> value` (Laravel's 3-argument `->where(...)`) -
    /// for comparisons `where_eq` can't express (`!=`, `>`, `>=`, `<`,
    /// `<=`, `LIKE`).
    #[must_use]
    pub fn where_op(mut self, column: &'static str, op: Op, value: impl Into<BindValue>) -> Self {
        self.wheres
            .push((Conj::And, Condition::Op(column, op, value.into())));
        self
    }

    /// `WHERE column IS NULL`.
    #[must_use]
    pub fn where_null(mut self, column: &'static str) -> Self {
        self.wheres.push((Conj::And, Condition::Null(column)));
        self
    }

    /// `WHERE column IS NOT NULL`.
    #[must_use]
    pub fn where_not_null(mut self, column: &'static str) -> Self {
        self.wheres.push((Conj::And, Condition::NotNull(column)));
        self
    }

    /// `WHERE column IN (values...)` (Laravel's `->whereIn(...)`) - used by
    /// relationship batch loaders (`load_*`, see `larust-macros`'
    /// `relations.rs`) to fetch every related row for a whole batch of
    /// already-loaded rows in one query instead of one query per row.
    /// `values` empty is a real case (batch-loading relations for an empty
    /// input slice), not just a hypothetical - rendering treats it as a
    /// condition that matches nothing (`1=0`), since `"col" IN ()` is
    /// invalid SQL in SQLite (a syntax error, not an empty-result query).
    #[must_use]
    pub fn where_in<V: Into<BindValue>>(mut self, column: &'static str, values: Vec<V>) -> Self {
        self.wheres.push((
            Conj::And,
            Condition::In(column, values.into_iter().map(Into::into).collect()),
        ));
        self
    }

    /// `OR column = value`.
    #[must_use]
    pub fn or_where_eq(mut self, column: &'static str, value: impl Into<BindValue>) -> Self {
        self.wheres
            .push((Conj::Or, Condition::Eq(column, value.into())));
        self
    }

    /// `OR column <op> value`.
    #[must_use]
    pub fn or_where_op(
        mut self,
        column: &'static str,
        op: Op,
        value: impl Into<BindValue>,
    ) -> Self {
        self.wheres
            .push((Conj::Or, Condition::Op(column, op, value.into())));
        self
    }

    /// `OR column IN (values...)`.
    #[must_use]
    pub fn or_where_in<V: Into<BindValue>>(mut self, column: &'static str, values: Vec<V>) -> Self {
        self.wheres.push((
            Conj::Or,
            Condition::In(column, values.into_iter().map(Into::into).collect()),
        ));
        self
    }

    /// `OR column IS NULL`.
    #[must_use]
    pub fn or_where_null(mut self, column: &'static str) -> Self {
        self.wheres.push((Conj::Or, Condition::Null(column)));
        self
    }

    /// A parenthesized `AND (...)` group - `f` receives an empty builder
    /// over this same table and whatever conditions it adds (via its own
    /// return value) become the group's contents; nothing else about the
    /// builder `f` receives (table/order/limit) is used. Exists so an
    /// `OR` added *inside* the group doesn't leak out and change the
    /// precedence of conditions already on `self` - see `scope`'s own doc
    /// comment for the same concern, solved automatically there.
    #[must_use]
    pub fn where_group(self, f: impl FnOnce(Self) -> Self) -> Self {
        self.push_group(Conj::And, f)
    }

    /// `OR (...)` - see `where_group`.
    #[must_use]
    pub fn or_where_group(self, f: impl FnOnce(Self) -> Self) -> Self {
        self.push_group(Conj::Or, f)
    }

    fn push_group(mut self, conj: Conj, f: impl FnOnce(Self) -> Self) -> Self {
        let group_wheres = f(Self::new(self.table)).wheres;
        self.wheres.push((conj, Condition::Group(group_wheres)));
        self
    }

    /// A reusable, named `WHERE` preset (Eloquent's local scopes), e.g.:
    ///
    /// ```ignore
    /// impl Post {
    ///     pub fn published(q: QueryBuilder<Self>) -> QueryBuilder<Self> {
    ///         q.where_not_null(Self::PUBLISHED_AT)
    ///     }
    /// }
    /// Post::query().scope(Post::published).latest(Post::ID).get().await?;
    /// ```
    ///
    /// Unlike `where_group`, a scope's own conditions are only wrapped in
    /// a parenthesized group when they actually contain an `OR` - an
    /// all-`AND` scope body is flattened directly into `self` instead,
    /// since plain `AND`s are associative with whatever else is on
    /// `self` and don't need the parens. This is specifically what
    /// prevents the classic Eloquent scope-precedence leak: a scope whose
    /// own body uses `OR` (`Post::recent_or_pinned`, say) can be combined
    /// with other conditions on `self` without that internal `OR`
    /// silently changing what the *rest* of the query matches.
    #[must_use]
    pub fn scope(mut self, f: impl FnOnce(Self) -> Self) -> Self {
        let scope_wheres = f(Self::new(self.table)).wheres;
        let needs_group = scope_wheres
            .iter()
            .any(|(conj, _)| matches!(conj, Conj::Or));
        if needs_group {
            self.wheres
                .push((Conj::And, Condition::Group(scope_wheres)));
        } else {
            self.wheres.extend(scope_wheres);
        }
        self
    }

    /// `WHERE column IN (SELECT sub_column FROM ... [WHERE ...])` - a
    /// subquery filter against a *different* model's table, built from
    /// `sub`'s own current state (table + whatever `where_*` it's already
    /// chained) - its own conditions, not `self`'s, become the
    /// subquery's `WHERE` clause. See `Condition::InQuery`'s own doc
    /// comment for why this is a subquery, not a real `JOIN`.
    #[must_use]
    pub fn where_in_query<U>(
        mut self,
        column: &'static str,
        sub_column: &'static str,
        sub: QueryBuilder<U>,
    ) -> Self {
        self.wheres.push((
            Conj::And,
            Condition::InQuery {
                column,
                sub_table: sub.table,
                sub_column,
                sub_wheres: sub.wheres,
            },
        ));
        self
    }

    /// Orders by `column` descending (Laravel's `->latest($column)`).
    /// Each call *adds* a sort key rather than replacing the last one -
    /// matching Eloquent's own `->orderBy(...)` chaining.
    #[must_use]
    pub fn latest(mut self, column: &'static str) -> Self {
        self.order_by.push((column, Order::Desc));
        self
    }

    /// Orders by `column` ascending (Laravel's `->oldest($column)`).
    #[must_use]
    pub fn oldest(mut self, column: &'static str) -> Self {
        self.order_by.push((column, Order::Asc));
        self
    }

    /// `->orderBy($column, $direction)` - `latest`/`oldest` are sugar for
    /// this with a fixed direction.
    #[must_use]
    pub fn order_by(mut self, column: &'static str, direction: Order) -> Self {
        self.order_by.push((column, direction));
        self
    }

    /// Caps the number of rows returned, independent of `paginate` (which
    /// sets this internally). No public `.offset()` yet - SQLite/MySQL/
    /// Postgres disagree on whether `OFFSET` needs a `LIMIT` alongside it
    /// (MySQL requires one; Postgres doesn't), and nothing in this
    /// codebase needs offset-without-limit yet to justify picking one of
    /// the backend-specific workarounds.
    #[must_use]
    pub fn limit(mut self, n: i64) -> Self {
        self.limit = Some(n);
        self
    }

    /// A stand-in for Laravel's `->paginate($perPage)` - limits to
    /// `per_page` rows. Page-number/metadata support (current page, total
    /// count, links) is a later addition; for now this is equivalent to
    /// `.limit(per_page).get()`.
    pub async fn paginate(mut self, per_page: i64) -> Result<Vec<T>, AppError> {
        if per_page <= 0 {
            return Err(AppError::Http {
                status: axum::http::StatusCode::UNPROCESSABLE_ENTITY,
                message: "pagination size must be greater than zero".to_string(),
            });
        }
        self.limit = Some(per_page);
        self.get().await
    }

    pub async fn get(self) -> Result<Vec<T>, AppError> {
        self.get_on(pool()?).await
    }

    /// Executes this query against an explicit pool. This is the preferred
    /// building block for applications moving away from process-wide ORM
    /// state, while `get()` remains compatible with existing models.
    pub async fn get_on(self, database: &AnyPool) -> Result<Vec<T>, AppError> {
        let sql = self.build_sql(backend(), None);
        let combined = self.soft_delete_combined_wheres();
        let wheres = combined.as_deref().unwrap_or(&self.wheres);
        let query = bind_all(sqlx::query_as::<_, T>(&sql), wheres);
        query
            .fetch_all(database)
            .await
            .map_err(|e| AppError::Internal(Box::new(e)))
    }

    pub async fn first(self) -> Result<Option<T>, AppError> {
        self.first_on(pool()?).await
    }

    pub async fn first_on(self, database: &AnyPool) -> Result<Option<T>, AppError> {
        let sql = self.build_sql(backend(), Some(1));
        let combined = self.soft_delete_combined_wheres();
        let wheres = combined.as_deref().unwrap_or(&self.wheres);
        let query = bind_all(sqlx::query_as::<_, T>(&sql), wheres);
        query
            .fetch_optional(database)
            .await
            .map_err(|e| AppError::Internal(Box::new(e)))
    }

    pub async fn count(self) -> Result<i64, AppError> {
        self.count_on(pool()?).await
    }

    pub async fn count_on(self, database: &AnyPool) -> Result<i64, AppError> {
        let sql = self.build_count_sql(backend());
        let combined = self.soft_delete_combined_wheres();
        let wheres = combined.as_deref().unwrap_or(&self.wheres);
        let query = bind_all(sqlx::query_as::<_, (i64,)>(&sql), wheres);
        query
            .fetch_one(database)
            .await
            .map(|(count,)| count)
            .map_err(|e| AppError::Internal(Box::new(e)))
    }

    pub async fn exists(self) -> Result<bool, AppError> {
        Ok(self.first().await?.is_some())
    }

    /// `backend` is passed in explicitly (rather than read from the
    /// process-wide `larust_orm::backend()` singleton internally) purely so
    /// this stays unit-testable - that singleton's `OnceLock` can only be
    /// set once per process, so a single test binary could never otherwise
    /// exercise both the `?` (SQLite/MySQL) and `$N` (Postgres) render
    /// paths side by side. Every real caller (`get_on`/`first_on`/
    /// `count_on` above) still resolves it from the same global `backend()`
    /// every other framework crate already reads.
    fn build_sql(&self, backend: Backend, first_limit: Option<i64>) -> String {
        // Every identifier here is quoted (`"..."`) - `self.table` and each
        // `column` are always `&'static str` constants generated by
        // `#[derive(Model)]` from a table/field name, never runtime data,
        // so quoting is about not colliding with a SQL reserved keyword
        // (a field named `order`, say), not about injection.
        let mut sql = format!("SELECT * FROM \"{}\"", self.table);

        let combined = self.soft_delete_combined_wheres();
        let wheres = combined.as_deref().unwrap_or(&self.wheres);
        if !wheres.is_empty() {
            let mut next_placeholder = 1usize;
            sql.push_str(" WHERE ");
            sql.push_str(&render_wheres(wheres, backend, &mut next_placeholder));
        }

        if !self.order_by.is_empty() {
            let parts: Vec<String> = self
                .order_by
                .iter()
                .map(|(column, direction)| {
                    let direction = match direction {
                        Order::Asc => "ASC",
                        Order::Desc => "DESC",
                    };
                    format!("\"{column}\" {direction}")
                })
                .collect();
            sql.push_str(&format!(" ORDER BY {}", parts.join(", ")));
        }

        if let Some(limit) = first_limit.or(self.limit) {
            sql.push_str(&format!(" LIMIT {limit}"));
        }

        sql
    }

    fn build_count_sql(&self, backend: Backend) -> String {
        let mut sql = format!("SELECT COUNT(*) FROM \"{}\"", self.table);
        let combined = self.soft_delete_combined_wheres();
        let wheres = combined.as_deref().unwrap_or(&self.wheres);
        if !wheres.is_empty() {
            let mut next_placeholder = 1usize;
            sql.push_str(" WHERE ");
            sql.push_str(&render_wheres(wheres, backend, &mut next_placeholder));
        }
        sql
    }

    /// `None` when nothing needs combining (the common case: most models
    /// aren't soft-deletable at all, or the caller explicitly asked for
    /// every row via `with_trashed()`) - callers then use `&self.wheres`
    /// directly with no extra allocation. `Some(combined)` otherwise: the
    /// soft-delete filter condition, combined with `self.wheres` -
    /// wrapped in a `Group` only if `self.wheres` itself has a top-level
    /// `OR` (same reasoning as `scope`'s own precedence-safe grouping),
    /// since a bare, un-parenthesized `"deleted_at" IS NULL AND a OR b`
    /// would otherwise only bind to `a`, not the whole clause.
    fn soft_delete_combined_wheres(&self) -> Option<Vec<(Conj, Condition)>> {
        let (column, filter) = self.soft_delete?;
        let filter_condition = match filter {
            SoftDeleteFilter::WithTrashed => return None,
            SoftDeleteFilter::Normal => Condition::Null(column),
            SoftDeleteFilter::OnlyTrashed => Condition::NotNull(column),
        };
        if self.wheres.is_empty() {
            return Some(vec![(Conj::And, filter_condition)]);
        }
        let has_top_level_or = self.wheres.iter().any(|(conj, _)| matches!(conj, Conj::Or));
        let mut combined = vec![(Conj::And, filter_condition)];
        if has_top_level_or {
            combined.push((Conj::And, Condition::Group(self.wheres.clone())));
        } else {
            combined.extend(self.wheres.iter().cloned());
        }
        Some(combined)
    }
}

/// Implemented automatically, only for a `#[derive(Model)]` struct marked
/// `#[soft_deletes]` - gates `with_trashed`/`only_trashed` (below) at
/// *compile* time, so calling either on a model that never opted in is a
/// compile error (no such method exists on `QueryBuilder<NotSoftDeleted>`),
/// not a silent no-op or a runtime error.
pub trait SoftDeletes: crate::Model {}

impl<T> QueryBuilder<T>
where
    T: for<'r> sqlx::FromRow<'r, sqlx::any::AnyRow> + Send + Unpin + SoftDeletes,
{
    /// Includes soft-deleted rows alongside normal ones (Eloquent's
    /// `withTrashed()`).
    #[must_use]
    pub fn with_trashed(mut self) -> Self {
        if let Some((column, _)) = self.soft_delete {
            self.soft_delete = Some((column, SoftDeleteFilter::WithTrashed));
        }
        self
    }

    /// Only soft-deleted rows (Eloquent's `onlyTrashed()`).
    #[must_use]
    pub fn only_trashed(mut self) -> Self {
        if let Some((column, _)) = self.soft_delete {
            self.soft_delete = Some((column, SoftDeleteFilter::OnlyTrashed));
        }
        self
    }
}

/// One `?` (SQLite/MySQL) or `$N` (Postgres, `next_placeholder`
/// incrementing left-to-right across the whole clause) - see `sqlx-core`'s
/// own doc comment (confirmed by reading its vendored source): Postgres and
/// SQLite accept `$1, $2, ...`; MySQL/MariaDB require `?`. SQLite is kept on
/// `?` here (not switched to `$N` even though it would also accept it) to
/// match this codebase's existing MySQL-sharing convention and avoid
/// touching working SQL text with no behavioral need to.
fn next_placeholder_str(backend: Backend, next_placeholder: &mut usize) -> String {
    match backend {
        Backend::Sqlite | Backend::MySql => "?".to_string(),
        Backend::Postgres => {
            let n = *next_placeholder;
            *next_placeholder += 1;
            format!("${n}")
        }
    }
}

/// Renders a full `AND`/`OR`-joined clause list with no surrounding
/// parens (the caller adds those for a `Group`) - shared by the
/// top-level `WHERE`, a `Group`'s own contents, and an `InQuery`'s
/// subquery `WHERE`, all of which are "a `wheres` list rendered in
/// order," recursively.
fn render_wheres(
    wheres: &[(Conj, Condition)],
    backend: Backend,
    next_placeholder: &mut usize,
) -> String {
    let mut out = String::new();
    for (i, (conj, condition)) in wheres.iter().enumerate() {
        if i > 0 {
            out.push_str(match conj {
                Conj::And => " AND ",
                Conj::Or => " OR ",
            });
        }
        out.push_str(&render_condition(condition, backend, next_placeholder));
    }
    out
}

/// Renders one condition's SQL fragment (no values - those are bound
/// separately by `bind_all`, in the same left-to-right order this
/// function's placeholders appear in - bind order is positional, so it
/// doesn't matter whether the SQL text says `?` or `$3`).
fn render_condition(
    condition: &Condition,
    backend: Backend,
    next_placeholder: &mut usize,
) -> String {
    match condition {
        Condition::Eq(column, _) => {
            format!(
                "\"{column}\" = {}",
                next_placeholder_str(backend, next_placeholder)
            )
        }
        Condition::Op(column, op, _) => {
            format!(
                "\"{column}\" {} {}",
                op.as_sql(),
                next_placeholder_str(backend, next_placeholder)
            )
        }
        // Empty IN-list: "col" IN () is a SQLite syntax error, not an
        // empty-result query - 1=0 is the standard always-false
        // substitute, so `where_in(col, vec![])` correctly yields zero
        // rows instead of failing the whole query.
        Condition::In(_, values) if values.is_empty() => "1=0".to_string(),
        Condition::In(column, values) => {
            let placeholders = values
                .iter()
                .map(|_| next_placeholder_str(backend, next_placeholder))
                .collect::<Vec<_>>()
                .join(", ");
            format!("\"{column}\" IN ({placeholders})")
        }
        Condition::Null(column) => format!("\"{column}\" IS NULL"),
        Condition::NotNull(column) => format!("\"{column}\" IS NOT NULL"),
        Condition::Group(inner) => {
            format!("({})", render_wheres(inner, backend, next_placeholder))
        }
        Condition::InQuery {
            column,
            sub_table,
            sub_column,
            sub_wheres,
        } => {
            let sub_where = if sub_wheres.is_empty() {
                String::new()
            } else {
                format!(
                    " WHERE {}",
                    render_wheres(sub_wheres, backend, next_placeholder)
                )
            };
            format!("\"{column}\" IN (SELECT \"{sub_column}\" FROM \"{sub_table}\"{sub_where})")
        }
    }
}

fn bind_all<'q, T>(
    mut query: QueryAs<'q, Any, T, AnyArguments<'q>>,
    wheres: &'q [(Conj, Condition)],
) -> QueryAs<'q, Any, T, AnyArguments<'q>> {
    for (_, condition) in wheres {
        query = bind_condition(query, condition);
    }
    query
}

/// Recurses into `Group`/`InQuery` in the same left-to-right order
/// `render_condition`/`render_wheres` render them, so bind order (purely
/// positional - `sqlx` doesn't care whether the SQL text said `?` or
/// `$3`) always lines up with the placeholders those functions emitted.
fn bind_condition<'q, T>(
    mut query: QueryAs<'q, Any, T, AnyArguments<'q>>,
    condition: &'q Condition,
) -> QueryAs<'q, Any, T, AnyArguments<'q>> {
    match condition {
        Condition::Eq(_, value) | Condition::Op(_, _, value) => {
            query = bind_value(query, value);
        }
        Condition::In(_, values) => {
            for value in values {
                query = bind_value(query, value);
            }
        }
        Condition::Null(_) | Condition::NotNull(_) => {}
        Condition::Group(inner) => {
            query = bind_all(query, inner);
        }
        Condition::InQuery { sub_wheres, .. } => {
            query = bind_all(query, sub_wheres);
        }
    }
    query
}

fn bind_value<'q, T>(
    query: QueryAs<'q, Any, T, AnyArguments<'q>>,
    value: &'q BindValue,
) -> QueryAs<'q, Any, T, AnyArguments<'q>> {
    match value {
        BindValue::Text(s) => query.bind(s),
        BindValue::Int(i) => query.bind(i),
        BindValue::Bool(b) => query.bind(b),
    }
}

